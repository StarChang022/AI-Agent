def load_existing_cache():
    """載入既有的暫存檔，若不存在或損壞則返回空字典"""
    merged_data = {}
    if os.path.exists(TEMP_JSON_PATH):
        try:
            with open(TEMP_JSON_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, list):
                for item in data:
                    name = item.get("company_name")
                    if name:
                        merged_data[name.strip()] = item
            elif isinstance(data, dict):
                for name, item in data.items():
                    merged_data[name.strip()] = item
            print(f"✅ 已載入既有暫存，共 {len(merged_data)} 筆公司資料。")
        except Exception as e:
            print(f"⚠️ 載入暫存檔失敗: {e}，將建立新的暫存。")
    return merged_data

def save_cache(cache_data):
    """保存暫存資料"""
    os.makedirs(os.path.dirname(TEMP_JSON_PATH), exist_ok=True)
    with open(TEMP_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(cache_data, f, ensure_ascii=False, indent=2)

def main():
    print("=== 開始更新公司簡介與暫存 ===")

    # 1. 備份原始 CSV
    if not os.path.exists(CSV_PATH):
        print(f"❌ 找不到 CSV 檔案：{CSV_PATH}")
        return
    shutil.copy2(CSV_PATH, BACKUP_PATH)
    print(f"✅ 已成功備份 CSV 至：{BACKUP_PATH}")

    # 2. 載入 CSV
    with open(CSV_PATH, "r", encoding="utf-8-sig") as f:
        reader = csv.reader(f)
        rows = list(reader)

    if not rows:
        print("❌ CSV 檔案內容為空")
        return

    header = rows[0]
    try:
        name_idx = header.index("公司名稱")
        desc_idx = header.index("說明")
    except ValueError as e:
        print(f"❌ CSV 標頭缺少必要欄位：{e}")
        return

    # 3. 載入並更新暫存檔
    cache_data = load_existing_cache()
    
    # 4. 更新 CSV 與暫存記憶體
    updated_rows_count = 0
    updated_companies_count = 0
    
    # 建立公司與其原始說明的對照，以便記錄到 JSON 暫存
    unique_companies = {}
    for idx in range(1, len(rows)):
        row = rows[idx]
        if not row or len(row) <= max(name_idx, desc_idx):
            continue
        comp_name = row[name_idx].strip()
        original_desc = row[desc_idx].strip()
        if comp_name:
            if comp_name not in unique_companies:
                unique_companies[comp_name] = original_desc

    # 更新暫存資料與對照表
    for comp_name, original_desc in unique_companies.items():
        if comp_name in INTRO_MAPPING:
            new_desc = INTRO_MAPPING[comp_name]
            
            # 更新或建立暫存項目，保留其他已有的欄位，僅合併/覆寫公司簡介相關欄位
            if comp_name not in cache_data or not isinstance(cache_data[comp_name], dict):
                cache_data[comp_name] = {}
                
            cache_data[comp_name]["company_name"] = comp_name
            cache_data[comp_name]["original_description"] = original_desc
            cache_data[comp_name]["new_description"] = new_desc
            cache_data[comp_name]["summary"] = new_desc
            updated_companies_count += 1

    # 5. 更新 CSV 資料行（說明欄位）
    for idx in range(1, len(rows)):
        row = rows[idx]
        if not row or len(row) <= max(name_idx, desc_idx):
            continue
        comp_name = row[name_idx].strip()
        if comp_name in INTRO_MAPPING:
            row[desc_idx] = INTRO_MAPPING[comp_name]
            updated_rows_count += 1

    # 6. 一次性寫回檔案，保持 21 欄結構，完全不填寫或覆寫 Z 欄和 AA 欄
    with open(CSV_PATH, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    # 寫回暫存 JSON
    save_cache(cache_data)

    print(f"=== 任務完成 ===")
    print(f"✅ CSV 更新總列數: {updated_rows_count}")
    print(f"✅ 暫存檔已更新公司數: {updated_companies_count}")
    print(f"✅ 暫存檔已儲存於：{TEMP_JSON_PATH}")

if __name__ == "__main__":
    main()
