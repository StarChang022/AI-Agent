def main():
    if not os.path.exists(EXTRACTED_PATH):
        print("Extracted descriptions path not found!")
        return
        
    with open(EXTRACTED_PATH, 'r', encoding='utf-8') as f:
        extracted = json.load(f)
        
    temp_logs = []
    for comp_name, orig_desc in extracted.items():
        new_desc = INTRO_MAPPING.get(comp_name, "")
        if not new_desc:
            print(f"Warning: No new description for {comp_name}")
        temp_logs.append({
            "company_name": comp_name,
            "original_description": orig_desc,
            "new_description": new_desc
        })
        
    with open(TEMP_JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(temp_logs, f, ensure_ascii=False, indent=2)
        
    print(f"Successfully wrote {len(temp_logs)} items to {TEMP_JSON_PATH}")

if __name__ == '__main__':
    main()
