def main():
    print("=== 開始更新公司簡介 ===")

    # 1. 備份原始 CSV
    if not os.path.exists(CSV_PATH):
        print(f"❌ 找不到 CSV 檔案：{CSV_PATH}")
        return
    shutil.copy2(CSV_PATH, BACKUP_PATH)
    print(f"✅ 已成功備份 CSV 至：{BACKUP_PATH}")

    # 2. 讀取現有的 JSON 暫存檔以利合併
    cache_data = {}
    if os.path.exists(TEMP_JSON_PATH):
        try:
            with open(TEMP_JSON_PATH, "r", encoding="utf-8") as f:
                cache_data = json.load(f)
            print(f"✅ 已載入既有暫存 JSON 檔，共 {len(cache_data)} 筆公司資料。")
        except Exception as e:
            print(f"⚠️ 載入暫存 JSON 檔失敗: {e}，將建立新的暫存。")

    # 3. 讀取 CSV 全部資料至記憶體
    with open(CSV_PATH, 'r', encoding='utf-8-sig') as f:
        reader = csv.reader(f)
        rows = list(reader)

    if not rows:
        print("❌ CSV 檔案內容為空")
        return

    header = [h.strip() for h in rows[0]]
    try:
        name_idx = header.index("公司名稱")
        desc_idx = header.index("說明")
    except ValueError as e:
        print(f"❌ CSV 標頭缺少必要欄位：{e}")
        return

    print(f"  → 「公司名稱」欄位 Index: {name_idx}, 「說明」欄位 Index: {desc_idx}")

    # 4. 在記憶體中逐行更新「說明」欄位，並將新資料放入暫存 JSON 結構中
    csv_updated_count = 0
    json_added_count = 0

    # 追蹤我們在這批 CSV 中看過的每一家公司的 row_index (資料列是 1-indexed)
    csv_row_counter = 0

    for idx in range(1, len(rows)):
        row = rows[idx]
        if not row or len(row) <= max(name_idx, desc_idx):
            continue

        csv_row_counter += 1
        comp_name = row[name_idx].strip()
        orig_desc = row[desc_idx].strip()

        # 比對我們的對照表
        match_key = None
        for key in INTRO_MAPPING:
            # 去除空白比對，避免因 Cosen 公司名字中有 tab 或多餘空格造成的匹配失敗
            if "".join(key.split()) == "".join(comp_name.split()):
                match_key = key
                break

        if match_key:
            new_desc = INTRO_MAPPING[match_key]
            # 更新記憶體中的 CSV 欄位
            row[desc_idx] = new_desc
            csv_updated_count += 1

            # 更新/新增至 JSON 暫存
            # 如果這家公司已經在 JSON 暫存中，只更新 new_description 與 summary
            # 如果不在，則建立全新項目
            if comp_name not in cache_data:
                cache_data[comp_name] = {
                    "row_index": csv_row_counter,
                    "company_name": comp_name,
                    "original_description": orig_desc,
                    "new_description": new_desc,
                    "summary": new_desc
                }
                json_added_count += 1
            else:
                cache_data[comp_name]["new_description"] = new_desc
                cache_data[comp_name]["summary"] = new_desc
                # 如果 original_description 為空或需要更新則填補
                if not cache_data[comp_name].get("original_description"):
                    cache_data[comp_name]["original_description"] = orig_desc

    # 5. 一次性寫回 CSV
    with open(CSV_PATH, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerows(rows)
    print(f"✅ 已完成寫回 CSV 檔案！共更新 {csv_updated_count} 行資料。")

    # 6. 一次性寫入暫存 JSON 檔
    os.makedirs(os.path.dirname(TEMP_JSON_PATH), exist_ok=True)
    with open(TEMP_JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(cache_data, f, ensure_ascii=False, indent=2)
    print(f"✅ 暫存對照表已完成寫入與合併！目前總筆數：{len(cache_data)} (本批新増：{json_added_count} 筆)。")

if __name__ == '__main__':
    main()
