def main():
    if not os.path.exists(CSV_PATH):
        print(f"❌ 找不到 CSV 檔案：{CSV_PATH}")
        return

    # 一次性讀取 CSV 至記憶體 (使用 utf-8-sig 以便相容 BOM)
    with open(CSV_PATH, 'r', encoding='utf-8-sig') as f:
        reader = csv.reader(f)
        rows = list(reader)

    if not rows:
        print("❌ CSV 內容為空")
        return

    header = rows[0]
    try:
        name_idx = header.index("公司名稱")
        desc_idx = header.index("說明")
    except ValueError as e:
        print(f"❌ 缺少必要欄位：{e}")
        return

    print(f"ℹ️ 「公司名稱」Index: {name_idx}, 「說明」Index: {desc_idx}")

    updated_count = 0
    skipped_count = 0
    temp_records = []

    # 在記憶體中逐行更新說明欄位
    for idx in range(1, len(rows)):
        row = rows[idx]
        if not row or len(row) <= max(name_idx, desc_idx):
            continue
        
        comp_name = row[name_idx].strip()

        if comp_name in INTRO_MAPPING:
            new_desc = INTRO_MAPPING[comp_name]
            row[desc_idx] = new_desc
            updated_count += 1
            # 存入暫存記錄
            temp_records.append({
                "company_name": comp_name,
                "new_description": new_desc
            })
        else:
            skipped_count += 1

    # 最後執行一次覆寫操作寫回 CSV
    with open(CSV_PATH, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    print(f"✅ CSV 覆寫成功。更新筆數: {updated_count}, 跳過/無須更新筆數: {skipped_count}")

    # 寫入暫存 JSON 檔案
    os.makedirs(os.path.dirname(TEMP_JSON_PATH), exist_ok=True)
    with open(TEMP_JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(temp_records, f, ensure_ascii=False, indent=2)
    
    print(f"✅ 暫存 JSON 寫入成功：{TEMP_JSON_PATH}")

if __name__ == '__main__':
    main()
