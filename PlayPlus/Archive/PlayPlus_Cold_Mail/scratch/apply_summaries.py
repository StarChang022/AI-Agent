def main():
    # 1. Update temporary_104.json
    if not os.path.exists(json_path):
        print(f"JSON file not found: {json_path}")
        return
        
    with open(json_path, 'r', encoding='utf-8') as f:
        records = json.load(f)
        
    for r in records:
        idx = r["row_idx"]
        if idx in summaries:
            r["summary"] = summaries[idx]
            
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(records, f, ensure_ascii=False, indent=2)
    print("Updated temporary_104.json with summaries.")
    
    # 2. Update 名單副本.csv
    if not os.path.exists(csv_path):
        print(f"CSV file not found: {csv_path}")
        return
        
    rows = []
    with open(csv_path, mode='r', encoding='utf-8') as f:
        reader = csv.reader(f)
        header = next(reader)
        rows.append(header)
        
        # We need to find the index of "說明"
        desc_idx = -1
        for i, col in enumerate(header):
            if col == "說明":
                desc_idx = i
                break
                
        if desc_idx == -1:
            print("Could not find '說明' column in CSV header.")
            return
            
        # We map rows to records using their 0-based data row index
        for idx, row in enumerate(reader):
            if idx in summaries:
                # Overwrite description column
                row[desc_idx] = summaries[idx]
            rows.append(row)
            
    # Write back in a single operation
    with open(csv_path, mode='w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerows(rows)
    print(f"Successfully overwrote and saved {csv_path}")

if __name__ == "__main__":
    main()
